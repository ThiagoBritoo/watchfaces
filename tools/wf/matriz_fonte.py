GLIFOS = {k: [[int(c) for c in lin] for lin in v.split()] for k, v in _G.items()}


def tamanho(passo: int, pad: int) -> tuple[int, int]:
    return int(round(5 * passo + 2 * pad)), int(round(7 * passo + 2 * pad))


def glifo(ch: str, passo: int, raio: float, pad: int, apagado: float = 0.0, halo: bool = True) -> Image.Image:
    """Um caractere em matriz de pontos. `apagado` = opacidade (0..1) dos pontos desligados; `halo` = brilho em volta."""
    w, h = tamanho(passo, pad)
    s = 4
    g = GLIFOS[ch]
    lig = Image.new("L", (w * s, h * s), 0)
    apg = Image.new("L", (w * s, h * s), 0)
    dl, da = ImageDraw.Draw(lig), ImageDraw.Draw(apg)
    for y in range(7):
        for x in range(5):
            cx, cy = (pad + x * passo + passo / 2) * s, (pad + y * passo + passo / 2) * s
            (dl if g[y][x] else da).ellipse([cx - raio * s, cy - raio * s, cx + raio * s, cy + raio * s], fill=255)
    lig = lig.resize((w, h), Image.LANCZOS)
    apg = apg.resize((w, h), Image.LANCZOS)
    a = np.asarray(lig, np.float32)
    if halo:
        a = np.maximum(a, np.asarray(lig.filter(ImageFilter.GaussianBlur(max(1.0, passo * 0.45))), np.float32) * 0.5)
    a = np.maximum(a, np.asarray(apg, np.float32) * apagado)
    out = np.zeros((h, w, 4), np.uint8)
    out[..., :3] = 255
    out[..., 3] = np.clip(a, 0, 255).astype(np.uint8)
    return Image.fromarray(out, "RGBA")
